// Extracts the logo, the wordmark and the line icons from the wallet's own source, so the video uses
// exactly the same drawings as the app (src/components/Brand.tsx, src/components/icons.tsx).
//   node promo/lib/gen-brand.mjs   ->  promo/lib/brand-data.js
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const brand = readFileSync(join(ROOT, 'src/components/Brand.tsx'), 'utf8');
const icons = readFileSync(join(ROOT, 'src/components/icons.tsx'), 'utf8');

const WORDMARK = brand.match(/const WORDMARK =\s*'([^']+)'/)[1];
const master = (name) => {
  const m = brand.match(new RegExp(`(?:${name}): \\{[\\s\\S]*?body: '([^']+)',[\\s\\S]*?facet: '([^']+)',[\\s\\S]*?crop: '([^']+)'`));
  return { body: m[1], facet: m[2], crop: m[3] };
};
const FULL = master('full');
const SMALL = master("'16'");

// icons.tsx: `name: (<>...</>),` blocks inside PATHS.
const ICONS = {};
const block = icons.match(/const PATHS = \{([\s\S]*?)\n\} as const|const PATHS = \{([\s\S]*?)\n\};/);
const src = block ? block[1] ?? block[2] : '';
for (const m of src.matchAll(/\n  (\w+): \(\s*<>([\s\S]*?)<\/>\s*\),/g)) {
  ICONS[m[1]] = m[2]
    .replace(/\s+/g, ' ')
    .replace(/strokeLinecap/g, 'stroke-linecap')
    .replace(/strokeLinejoin/g, 'stroke-linejoin')
    .replace(/strokeWidth/g, 'stroke-width')
    .trim();
}

const out = `// GENERATED by promo/lib/gen-brand.mjs from the wallet's source. Do not edit.
export const WORDMARK = ${JSON.stringify(WORDMARK)};
export const MARK_FULL = ${JSON.stringify(FULL)};
export const MARK_SMALL = ${JSON.stringify(SMALL)};
export const ICONS = ${JSON.stringify(ICONS, null, 1)};
`;
writeFileSync(join(ROOT, 'promo/lib/brand-data.js'), out);
console.log('icons:', Object.keys(ICONS).join(', '));
